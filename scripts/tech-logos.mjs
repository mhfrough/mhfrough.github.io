// Technology logos for the case-study stack pills, from Simple Icons (https://simpleicons.org, CC0 unless an
// icon's own licence says otherwise; brands belong to their owners).
//   node scripts/tech-logos.mjs [--si <path to an unpacked simple-icons package>]
// The package is not a site dependency. Unpack it once into .devcache:
//   cd .devcache && mkdir -p simple-icons && cd simple-icons && npm pack simple-icons@13 && tar xzf simple-icons-*.tgz
// Output: public/images/tech/<slug>.svg (filled with the brand colour) and
// src/app/pages/case-studies/stack/tech-logos.ts (slug -> file + whether the circle needs a dark ground).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { CACHE, ROOT } from './_env.mjs';

const i = process.argv.indexOf('--si');
const SI = i > -1 ? resolve(ROOT, process.argv[i + 1]) : resolve(CACHE, 'simple-icons/package');

/** Slugs in use, with an optional colour override (Simple Icons ships Angular in near-black; the red reads better). */
const LOGOS = {
  angular: 'DD0031',
  typescript: null,
  reactivex: null,
  bootstrap: null,
  socketdotio: null,
  nestjs: null,
  nodedotjs: null,
  postgresql: null,
  typeorm: null,
  supabase: null,
  jsonwebtokens: null,
  passport: null,
  swagger: null,
  cloudflare: null,
  flutter: null,
  dart: null,
  googlemaps: null,
  whatsapp: null,
  springboot: null,
  openjdk: null,
  youtube: null,
  php: null,
  javascript: null,
  gulp: null,
  wordpress: null,
  firebase: null,
  sass: null,
  sharp: null,
  kotlin: null,
  primeng: null,
  materialdesign: null,
  paypal: null,
  stripe: null,
  i18next: null,
};

const data = JSON.parse(readFileSync(resolve(SI, '_data/simple-icons.json'), 'utf8'));
const icons = Array.isArray(data) ? data : data.icons;
const OUT = resolve(ROOT, 'public/images/tech');
mkdirSync(OUT, { recursive: true });

/** Relative luminance of a hex colour (WCAG). */
const lum = (hex) => {
  const c = [0, 2, 4].map((k) => parseInt(hex.slice(k, k + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};

const manifest = {};
for (const [slug, override] of Object.entries(LOGOS)) {
  const svg = readFileSync(resolve(SI, `icons/${slug}.svg`), 'utf8');
  const title = svg.match(/<title>(.*?)<\/title>/)?.[1] ?? slug;
  const meta = icons.find((x) => x.title.replace(/&amp;/g, '&') === title.replace(/&amp;/g, '&'));
  const hex = (override ?? meta?.hex ?? '1a1a1a').toUpperCase();
  const out = svg
    .replace(/<title>.*?<\/title>/, '')
    .replace(' role="img"', '')
    .replace('<svg ', `<svg fill="#${hex}" `);
  writeFileSync(resolve(OUT, `${slug}.svg`), out);
  // Light brand colours (JavaScript yellow, Supabase green...) sit on a dark circle so they stay visible.
  manifest[slug] = { src: `/images/tech/${slug}.svg`, dark: lum(hex) > 0.45 };
}

const ts = `// Generated by scripts/tech-logos.mjs. Do not edit by hand.
// Logos from Simple Icons (simpleicons.org); each brand belongs to its owner.
/** Simple Icons slug -> SVG in the brand colour, and whether its circle needs a dark ground. */
export const TECH_LOGOS: Readonly<Record<string, { src: string; dark: boolean }>> = ${JSON.stringify(manifest, null, 2)};
`;
const tsFile = resolve(ROOT, 'src/app/pages/case-studies/stack/tech-logos.ts');
mkdirSync(resolve(tsFile, '..'), { recursive: true });
writeFileSync(tsFile, ts);
console.log(`${Object.keys(manifest).length} logos -> public/images/tech, manifest -> ${tsFile}`);
