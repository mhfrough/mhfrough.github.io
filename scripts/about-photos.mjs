// About page photos: promo/about-photos/* -> public/images/about/*.webp + src/app/pages/about/about.photos.ts
//   npm run about:photos            (or: node scripts/about-photos.mjs --src <folder>)
// Images join the gallery in file-name order, so prefix names with 01-, 02- ... to set the order.
// Photos of the owner are never published (owner, 2026-10-11): a file named portrait.* is skipped.
// Captions and alt text come from
// promo/about-photos/captions.json ({ "hunza-2024.jpg": { "caption": "Hunza, 2024", "alt": "..." } }),
// else from the file name: "03-hunza-2024.jpg" -> "Hunza, 2024".
// sharp strips EXIF (GPS included) on output; .rotate() applies the camera orientation first.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { extname, parse, resolve } from 'node:path';
import sharp from 'sharp';
import { ROOT } from './_env.mjs';

const srcArg = process.argv.indexOf('--src');
const SRC = srcArg > 0 ? resolve(process.argv[srcArg + 1]) : resolve(ROOT, 'promo/about-photos');
const OUT = resolve(ROOT, 'public/images/about');
const DATA = resolve(ROOT, 'src/app/pages/about/about.photos.ts');
const EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.tif', '.tiff', '.heic', '.heif']);

const captions = existsSync(resolve(SRC, 'captions.json')) ? JSON.parse(readFileSync(resolve(SRC, 'captions.json'), 'utf8')) : {};
const files = existsSync(SRC)
  ? readdirSync(SRC)
      .filter((f) => EXT.has(extname(f).toLowerCase()) && parse(f).name.toLowerCase() !== 'portrait')
      .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
  : [];

const slug = (f) =>
  parse(f)
    .name.toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

/** "03-hunza-2024" -> "Hunza, 2024" */
function captionFromName(f) {
  const words = parse(f).name.replace(/^\d+[-_ ]+/, '').split(/[-_ ]+/).filter(Boolean);
  const year = words.length > 1 && /^(19|20)\d\d$/.test(words.at(-1)) ? words.pop() : null;
  const text = words.join(' ');
  const cap = text.charAt(0).toUpperCase() + text.slice(1);
  return year ? `${cap}, ${year}` : cap;
}

// Clear only the files this script writes; subfolders (hobbies/, made by hobby-covers.mjs) stay.
mkdirSync(OUT, { recursive: true });
for (const f of readdirSync(OUT)) {
  const p = resolve(OUT, f);
  if (statSync(p).isFile()) rmSync(p);
}

const gallery = [];

for (const f of files) {
  const input = resolve(SRC, f);
  const id = slug(f);
  const meta = captions[f] ?? {};
  try {
    const base = sharp(input).rotate();
    const full = await base.clone().resize(1600, 1600, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 78 }).toFile(resolve(OUT, `${id}.webp`));
    const thumb = await base.clone().resize({ width: 720, withoutEnlargement: true }).webp({ quality: 72 }).toFile(resolve(OUT, `${id}-sm.webp`));
    const caption = meta.caption ?? captionFromName(f);
    gallery.push({
      id,
      src: `/images/about/${id}.webp`,
      thumb: `/images/about/${id}-sm.webp`,
      w: full.width,
      h: full.height,
      tw: thumb.width,
      th: thumb.height,
      caption,
      alt: meta.alt ?? caption,
    });
  } catch (e) {
    console.warn(`about-photos: skipped ${f} (${e.message})`);
  }
}

const ts = `// Generated by scripts/about-photos.mjs (npm run about:photos). Do not edit by hand:
// add photos to promo/about-photos, set captions in promo/about-photos/captions.json, then re-run.

export interface AboutPhoto {
  id: string;
  src: string;
  thumb: string;
  w: number;
  h: number;
  tw: number;
  th: number;
  caption: string;
  alt: string;
}

export const GALLERY: readonly AboutPhoto[] = ${JSON.stringify(gallery, null, 2)};
`;
writeFileSync(DATA, ts);
console.log(`about-photos: ${gallery.length} gallery photos -> public/images/about`);
