// About page hobby covers: downloads cover art for the anime, films and games lists and writes tiny round-ready
// WebP thumbnails to public/images/about/hobbies/ plus src/app/pages/about/about.covers.ts.
//   npm run about:covers
// Sources: AniList public API (anime), Wikipedia page summary thumbnails (films), Steam CDN capsules (games).
// Titles must match about.copy.ts exactly; a title without a cover falls back to an icon in the template.
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import sharp from 'sharp';
import { ROOT } from './_env.mjs';

const OUT = resolve(ROOT, 'public/images/about/hobbies');
const DATA = resolve(ROOT, 'src/app/pages/about/about.covers.ts');
const SIZE = 64; // shown at 22-24px, so 64px stays sharp on 2x/3x screens
const UA = 'mhfrough.dev build script (https://mhfrough.dev)';

const ANIME = {
  'Violet Evergarden': 'Violet Evergarden',
  'Steins;Gate': 'Steins;Gate',
  Naruto: 'Naruto',
  'Pokémon': 'Pokemon',
  'Astra Lost in Space': 'Kanata no Astra',
};
const FILMS = {
  Interstellar: 'Interstellar_(film)',
  Inception: 'Inception',
  Predestination: 'Predestination_(film)',
  'Real Steel': 'Real_Steel',
};
const GAMES = {
  'Dota 2': 570,
  'GTA V': 271590,
  'Red Dead Redemption': 2668510,
  'Elden Ring': 1245620,
  'The Witcher 3': 292030,
};

const slug = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

async function get(url, init) {
  const res = await fetch(url, { ...init, headers: { 'User-Agent': UA, ...init?.headers } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res;
}

async function anime(search) {
  const query = 'query($s:String){Media(search:$s,type:ANIME,sort:SEARCH_MATCH){title{romaji english}coverImage{large}}}';
  const res = await get('https://graphql.anilist.co', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
    body: JSON.stringify({ query, variables: { s: search } }),
  });
  const m = (await res.json()).data.Media;
  return { url: m.coverImage.large, matched: m.title.english ?? m.title.romaji };
}

async function film(page) {
  const j = await (await get(`https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(page)}`)).json();
  return { url: (j.thumbnail ?? j.originalimage).source, matched: j.title };
}

async function game(appId) {
  // Portrait library capsule first (poster art), landscape header as a fallback.
  for (const file of ['library_600x900.jpg', 'header.jpg']) {
    const url = `https://cdn.cloudflare.steamstatic.com/steam/apps/${appId}/${file}`;
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (res.ok) return { url, matched: `Steam ${appId} ${file}` };
  }
  throw new Error(`no Steam art for ${appId}`);
}

mkdirSync(OUT, { recursive: true });
const jobs = [
  ...Object.entries(ANIME).map(([t, s]) => [t, () => anime(s)]),
  ...Object.entries(FILMS).map(([t, p]) => [t, () => film(p)]),
  ...Object.entries(GAMES).map(([t, id]) => [t, () => game(id)]),
];

const covers = {};
for (const [title, find] of jobs) {
  try {
    const { url, matched } = await find();
    const buf = Buffer.from(await (await get(url)).arrayBuffer());
    const file = `${slug(title)}.webp`;
    await sharp(buf)
      .resize(SIZE, SIZE, { fit: 'cover', position: sharp.strategy.attention })
      .webp({ quality: 80 })
      .toFile(resolve(OUT, file));
    covers[title] = `/images/about/hobbies/${file}`;
    console.log(`ok   ${title}  <-  ${matched}`);
  } catch (e) {
    console.warn(`skip ${title}: ${e.message}`);
  }
}

writeFileSync(
  DATA,
  `// Generated by scripts/hobby-covers.mjs. Do not edit by hand: run \`npm run about:covers\`.\n` +
    `/** Hobby title (as in about.copy.ts) -> ${SIZE}px square WebP cover, shown in a circle. */\n` +
    `export const COVERS: Readonly<Record<string, string>> = ${JSON.stringify(covers, null, 2)};\n`,
);
console.log(`\n${Object.keys(covers).length}/${jobs.length} covers -> ${OUT}`);
