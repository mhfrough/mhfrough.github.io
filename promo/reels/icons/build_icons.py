"""Build icons.js for the weather icons reel.

    python promo/reels/icons/build_icons.py

Inlines the 25 animated weather icons (public/images/weather-icons/animated) and the six tool icons
(mhfrough_projects/<tool>/icon.svg) as strings, so the reel can place several copies of one icon in the page
and the renderer's clock drives their CSS animations. Every copy needs its own names, so each icon's keyframes,
classes and ids are rewritten with a prefix token "@P@" that the reel replaces per copy. Every animated layer
(<g class="a ...">) gets data-l="<n>" so the reel can show one layer at a time.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
ICONS = REPO / "public" / "images" / "weather-icons" / "animated"
DATA = REPO / "src" / "app" / "pages" / "work" / "weather-icons" / "weather-icons.data.ts"
TOOLS = Path(r"D:/workspace-personal/mhfrough_projects")
TOOL_NAMES = ["flick", "sizzle", "scrawl", "pinch", "swoop", "jot"]


def scope(svg):
    style = re.search(r"<style>(.*?)</style>", svg, re.S)
    names = set()
    if style:
        css = style.group(1)
        names = set(re.findall(r"@keyframes ([\w-]+)", css)) | (set(re.findall(r"\.([A-Za-z][\w-]*)\{", css)) - {"a"})
    if names:
        pat = re.compile(r"(?<![\w#-])(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")(?![\w-])")
        svg = svg.replace(style.group(1), pat.sub(lambda m: "@P@-" + m.group(1), style.group(1)))
        svg = re.sub(r'class="([^"]*)"', lambda m: 'class="' + " ".join(
            "@P@-" + c if c in names else c for c in m.group(1).split()) + '"', svg)
    svg = re.sub(r'\bid="([^"]+)"', r'id="@P@-\1"', svg)
    svg = re.sub(r"url\(#([^)]+)\)", r"url(#@P@-\1)", svg)
    svg = re.sub(r"@media \(prefers-reduced-motion:reduce\)\{[^{}]*\{[^}]*\}\}", "", svg)
    svg = re.sub(r"<title>.*?</title>", "", svg)
    svg = re.sub(r'<svg([^>]*?) width="[\d.]+" height="[\d.]+"', r'<svg\1', svg, count=1)
    n = iter(range(1000))
    svg = re.sub(r'<g class="a ', lambda m: f'<g data-l="{next(n)}" class="a ', svg)
    return svg.replace("<svg ", '<svg aria-hidden="true" ', 1)


def main():
    data = DATA.read_text(encoding="utf-8")
    order = re.findall(r"id: '([^']+)',\s*name: '([^']+)',\s*group: '([^']+)'.*?motion: \[([^\]]*)\]", data, re.S)
    weather = [{"id": i, "name": n, "group": g, "motion": re.findall(r"'(\w+)'", m),
                "svg": scope((ICONS / f"{i}.svg").read_text(encoding="utf-8"))} for i, n, g, m in order]
    tools = [{"id": t, "name": t.capitalize(), "svg": scope((TOOLS / t / "icon.svg").read_text(encoding="utf-8"))}
             for t in TOOL_NAMES]
    out = HERE / "icons.js"
    out.write_text("// Generated by build_icons.py. Do not edit by hand.\nwindow.WEATHER = "
                   + json.dumps(weather) + ";\nwindow.TOOLS = " + json.dumps(tools) + ";\n", encoding="utf-8")
    print(out, len(weather), "weather icons,", len(tools), "tools,", out.stat().st_size // 1024, "KB")


if __name__ == "__main__":
    main()
